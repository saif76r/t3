/**
 * Query Hugging Face Pre-trained Models via Inference Client and Direct REST Router
 * Supports multiple API keys (e.g. HUGGINGFACE_API_KEY and HUGGINGFACE_API_KEY_2) with automatic failover.
 */
export async function queryHuggingFace(
  cropHint: string | undefined,
  base64Data: string,
  apiKey?: string
): Promise<StandardizedDiagnosis | null> {
  // Collect all available tokens
  const rawTokens = [
    apiKey,
    process.env.HUGGINGFACE_API_KEY,
    process.env.HUGGINGFACE_API_KEY_2,
    process.env.HF_TOKEN,
    process.env.HF_TOKEN_2,
  ].filter(Boolean) as string[];

  const tokens: string[] = [];
  for (const t of rawTokens) {
    for (const sub of t.split(',')) {
      const trimmed = sub.trim();
      if (trimmed && !tokens.includes(trimmed)) {
        tokens.push(trimmed);
      }
    }
  }

  if (tokens.length === 0) {
    return null;
  }

  // Determine candidate model based on crop hint
  const hint = (cropHint || '').toLowerCase();
  let candidateModels = [
    HUGGINGFACE_MODELS.vit_crop_leaf.id,
    HUGGINGFACE_MODELS.plant_village_mobilenet.id,
    HUGGINGFACE_MODELS.agri_resnet50.id,
  ];

  if (hint.includes('টমেটো') || hint.includes('tomato') || hint.includes('আলু') || hint.includes('potato')) {
    candidateModels = [
      HUGGINGFACE_MODELS.plant_village_mobilenet.id,
      HUGGINGFACE_MODELS.vit_crop_leaf.id,
      HUGGINGFACE_MODELS.agri_resnet50.id,
    ];
  } else if (hint.includes('ধান') || hint.includes('rice') || hint.includes('ভুট্টা') || hint.includes('corn')) {
    candidateModels = [
      HUGGINGFACE_MODELS.vit_crop_leaf.id,
      HUGGINGFACE_MODELS.agri_resnet50.id,
      HUGGINGFACE_MODELS.plant_village_mobilenet.id,
    ];
  }

  const imageBuffer = Buffer.from(base64Data, 'base64');

  // Try each model with token failover
  for (const modelId of candidateModels) {
    for (const token of tokens) {
      try {
        const hf = new HfInference(token);
        const res = await hf.imageClassification({
          model: modelId,
          data: imageBuffer,
        });

        if (Array.isArray(res) && res.length > 0) {
          const top = res[0];
          // Enforce high confidence threshold (at least 70%) to avoid guessing leaf diseases for cobs or fruits
          if (top.score && top.score >= 0.70) {
            const mapped = matchHuggingFaceClassToPrescription(top.label, top.score, cropHint);
            mapped.modelProvider = `Hugging Face (${modelId})`;
            return mapped;
          }
        }
      } catch (sdkErr: any) {
        // If SDK fails, fallback to direct REST API endpoint
        try {
          const endpoints = [
            `https://router.huggingface.co/hf-inference/models/${modelId}`,
            `https://api-inference.huggingface.co/models/${modelId}`,
          ];

          for (const url of endpoints) {
            const resp = await fetch(url, {
              method: 'POST',
              headers: {
                Authorization: `Bearer ${token}`,
                'Content-Type': 'application/octet-stream',
              },
              body: imageBuffer,
            });

            if (resp.ok) {
              const data: any = await resp.json();
              if (Array.isArray(data) && data.length > 0) {
                const top = data[0];
                // Strictly require top.score >= 0.70 (70%)
                if (top.label && top.score && top.score >= 0.70) {
                  const mapped = matchHuggingFaceClassToPrescription(top.label, top.score, cropHint);
                  mapped.modelProvider = `Hugging Face (${modelId})`;
                  return mapped;
                }
              }
            }
          }
        } catch (restErr: any) {
          console.warn(`Hugging Face attempt for ${modelId} notice:`, restErr?.message || restErr);
        }
      }
    }
  }

  return null;
}
